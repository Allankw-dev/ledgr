"""Tripwire for Alembic migrations.

A migration committed straight from `alembic revision --autogenerate` once dropped two tables and ~40 indexes (among
them the unique guard against recording the same M-Pesa payment twice) because Alembic could not see objects that
were created with raw SQL. It was named "add mpesa_mode" and added nothing. Autogenerate output must be read and
edited by hand before it is committed; a migration that still carries Alembic's "please adjust!" banner and removes
anything in upgrade() fails this test until someone has reviewed it and deleted the banner.
"""

import ast
from pathlib import Path

VERSIONS = Path(__file__).resolve().parent.parent / "alembic" / "versions"
BANNER = "auto generated by Alembic - please adjust"
DESTRUCTIVE = {"drop_table", "drop_index", "drop_column", "drop_constraint"}


def _destructive_calls_in_upgrade(source: str) -> list[str]:
    found = []
    for node in ast.parse(source).body:
        if isinstance(node, ast.FunctionDef) and node.name == "upgrade":
            for call in ast.walk(node):
                f = getattr(call, "func", None)
                if isinstance(call, ast.Call) and isinstance(f, ast.Attribute) and f.attr in DESTRUCTIVE:
                    if isinstance(f.value, ast.Name) and f.value.id == "op":
                        found.append(f.attr)
    return found


def test_there_are_migrations_to_check():
    assert len(list(VERSIONS.glob("*.py"))) > 10


def test_no_unreviewed_autogenerated_migration_drops_anything():
    offenders = {}
    for path in sorted(VERSIONS.glob("*.py")):
        source = path.read_text()
        if BANNER in source:
            drops = _destructive_calls_in_upgrade(source)
            if drops:
                offenders[path.name] = len(drops)
    assert not offenders, (
        f"Unreviewed autogenerated migration(s) that drop things: {offenders}. Read them, keep only what you mean to "
        "change, and delete the 'auto generated by Alembic - please adjust' line once you have."
    )


def test_the_tripwire_really_catches_the_original_mistake():
    bad = 'def upgrade():\n    # ### commands auto generated by Alembic - please adjust! ###\n    op.drop_table("invoice_outcomes")\n    op.drop_index("ux_payments_external_txn_id", table_name="payments")\n'
    assert _destructive_calls_in_upgrade(bad) == ["drop_table", "drop_index"]
    assert _destructive_calls_in_upgrade("def upgrade():\n    pass\n") == []
